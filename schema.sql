-- FD Rates Tracker - PostgreSQL schema
--
-- banks        : list of banks we track
-- fd_rates     : latest rate for each bank + FD type + tenure + deposit slab
-- rate_history : append-only log whenever a rate value changes

CREATE TABLE IF NOT EXISTS banks (
    slug        VARCHAR(80) PRIMARY KEY,
    name        VARCHAR(160) NOT NULL,
    created_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at  TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS fd_rates (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_slug       VARCHAR(80) NOT NULL,
    fd_type         VARCHAR(20) NOT NULL CHECK (fd_type IN ('callable', 'non_callable')),
    tenure_label    VARCHAR(160) NOT NULL,
    tenure_min_days INT NOT NULL,
    tenure_max_days INT NOT NULL,
    deposit_slab    VARCHAR(40) NOT NULL CHECK (deposit_slab IN ('<3 crore', '3 Cr < 5 Cr')),
    sort_order      INT NOT NULL DEFAULT 0,
    rate_percent    DECIMAL(5,2) NOT NULL,
    source_url      TEXT NULL,
    updated_at      TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_fd_rates_bank
        FOREIGN KEY (bank_slug) REFERENCES banks(slug)
        ON DELETE CASCADE,
    CONSTRAINT uq_fd_rates_current UNIQUE (bank_slug, fd_type, tenure_label, deposit_slab)
);

CREATE INDEX IF NOT EXISTS idx_fd_rates_bank ON fd_rates (bank_slug);
CREATE INDEX IF NOT EXISTS idx_fd_rates_lookup
    ON fd_rates (fd_type, tenure_label, deposit_slab, rate_percent DESC);

CREATE TABLE IF NOT EXISTS rate_history (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    bank_slug    VARCHAR(80) NOT NULL,
    fd_type      VARCHAR(20) NOT NULL CHECK (fd_type IN ('callable', 'non_callable')),
    tenure_label VARCHAR(160) NOT NULL,
    deposit_slab VARCHAR(40) NOT NULL CHECK (deposit_slab IN ('<3 crore', '3 Cr < 5 Cr')),
    rate_percent DECIMAL(5,2) NOT NULL,
    source_url   TEXT NULL,
    changed_at   TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_rate_history_bank
        FOREIGN KEY (bank_slug) REFERENCES banks(slug)
        ON DELETE CASCADE
);

CREATE INDEX IF NOT EXISTS idx_rate_history_bank_time
    ON rate_history (bank_slug, changed_at DESC);
